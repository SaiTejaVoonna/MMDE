// Builds the Cloudflare Pages output folder (dist/pages): the web files plus a generated config.js and _headers.
// Run by Cloudflare Pages as the build command (see docs/CLOUDFLARE.md) or by hand:  node scripts/pages-build.mjs
//   MMDE_API_BASE_URL = https://mmde-api.<you>.workers.dev   (a PUBLIC address, never a secret)  -> the site calls that Worker.
//   unset                                                       -> "browser-only" mode: the visitor's browser calls the public APIs itself.
// Nothing secret is read or written here. The TMDB token lives only in the Worker's secrets.
import { cpSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** The public services the page calls directly in browser-only mode (all verified to allow cross-origin calls from a web page). */
export const DIRECT_HOSTS = ['https://api.themoviedb.org', 'https://graphql.anilist.co', 'https://www.wikidata.org', 'https://en.wikipedia.org', 'https://musicbrainz.org', 'https://itunes.apple.com', 'https://api.animethemes.moe', 'https://api.tvmaze.com'];

/** Returns { configJs, headers }. Throws on an API address that is not a plain https origin. */
export function buildPagesConfig(apiBase) {
  const raw = String(apiBase ?? '').trim().replace(/\/+$/, '');
  let origin = '';
  if (raw) {
    let u;
    try { u = new URL(raw); } catch { throw new Error(`MMDE_API_BASE_URL is not a valid URL: ${raw}`); }
    if (u.protocol !== 'https:') throw new Error('MMDE_API_BASE_URL must start with https://');
    if (u.pathname !== '/' || u.search || u.hash || u.username || u.password) throw new Error('MMDE_API_BASE_URL must be just an origin, like https://mmde-api.example.workers.dev');
    origin = u.origin;
  }
  const config = origin ? { apiBaseUrl: origin } : { apiBaseUrl: '', mode: 'static' };
  const configJs = `// Generated by scripts/pages-build.mjs. PUBLIC values only.\nwindow.MMDE_CONFIG = ${JSON.stringify(config)};\n`;
  const connect = ["'self'", ...(origin ? [origin] : DIRECT_HOSTS)].join(' ');
  const csp = [
    "default-src 'self'", "script-src 'self'", "style-src 'self' 'unsafe-inline'", "img-src 'self' https: data:", `connect-src ${connect}`,
    "manifest-src 'self'", "worker-src 'self'", "base-uri 'none'", "form-action 'none'", "frame-ancestors 'none'",
  ].join('; ');
  const headers = [
    '/*', '  X-Content-Type-Options: nosniff', '  Referrer-Policy: no-referrer', '  X-Frame-Options: DENY',
    '  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=()', `  Content-Security-Policy: ${csp}`,
    '/*.js', '  Cache-Control: no-cache', '/index.html', '  Cache-Control: no-cache', '/sw.js', '  Cache-Control: no-cache', '/config.js', '  Cache-Control: no-cache', '',
  ].join('\n');
  return { configJs, headers, origin };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..');
  const out = join(root, 'dist', 'pages');
  const { configJs, headers, origin } = buildPagesConfig(process.env.MMDE_API_BASE_URL);
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  cpSync(join(root, 'web'), out, { recursive: true });
  writeFileSync(join(out, 'config.js'), configJs);
  writeFileSync(join(out, '_headers'), headers);
  console.log(`dist/pages ready (${origin ? `API: ${origin}` : 'browser-only mode'})`);
}
